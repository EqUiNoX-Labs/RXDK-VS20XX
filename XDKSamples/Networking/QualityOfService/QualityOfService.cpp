//-----------------------------------------------------------------------------
// Name: BeginOnlineListen()
// Desc: Initialize listener for online mode
//-----------------------------------------------------------------------------
VOID CXBoxSample::BeginOnlineListen()
{
    assert( m_bIsSignedIn );
    assert( m_bIsSessionRegistered );

    // Notify the world of our status
    DWORD dwState = XONLINE_FRIENDSTATE_FLAG_ONLINE;
    if( XBVoice_HasDevice() )
        dwState |= XONLINE_FRIENDSTATE_FLAG_VOICE;
    SetPlayerState( dwState );
            
    // Function required that we've registered an online session 
    // (m_xnSessionID) with Matchmaking

    // Default to listen when System Link is chosen
    m_bListen = TRUE;
    SetListenState( m_bListen );

    // Set the response data to our session name
    SetListenData( m_strSessionName, 
                   ( lstrlenW( m_strSessionName ) + 1 ) * sizeof(WCHAR) );
}




//-----------------------------------------------------------------------------
// Name: EndOnlineListen()
// Desc: Clean up from online mode
//-----------------------------------------------------------------------------
VOID CXBoxSample::EndOnlineListen()
{
    if( !m_bIsSignedIn )
        return;

    // Notify the world of our status
    SetPlayerState( XONLINE_FRIENDSTATE_FLAG_NONE );

    if( m_bIsSessionRegistered )
    {
        // Asynchronous session removal from Matchmaking service. This would normally
        // be pumped by the game in the main loop. For simplicity, this sample
        // pumps the deletion task to completion without yielding.
        CXBOnlineTask hDelete;
        HRESULT hr = XOnlineMatchSessionDelete( m_xnSessionID, NULL, &hDelete );
        if( SUCCEEDED(hr) )
        {
            for( hr = XONLINETASK_S_RUNNING; hr == XONLINETASK_S_RUNNING; )
                hr = hDelete.Continue();
        }

        // XNetUnregisterKey will automatically release the QoS listener
        INT iResult = XNetUnregisterKey( &m_xnSessionID );
        assert( iResult == NO_ERROR );
        (VOID)iResult;
        m_bIsSessionRegistered = FALSE;
        ZeroMemory( &m_xnSessionID, sizeof( XNKID ) );

        m_bIsSessionRegistered = FALSE;
    }

    // Sign off
    m_hOnlineTask.Close();
    m_bIsSignedIn = FALSE;
}




//-----------------------------------------------------------------------------
// Name: BeginSysLinkListen()
// Desc: Initialize for System Link mode
//-----------------------------------------------------------------------------
VOID CXBoxSample::BeginSysLinkListen()
{
    assert( !m_bIsSignedIn );

    if( !m_bIsSessionRegistered )
    {
        // Register the session for System Link
        INT iKeyCreated = XNetCreateKey( &m_xnSessionID, &m_xnKeyExchangeKey );
        assert( iKeyCreated == NO_ERROR );
        (VOID)iKeyCreated; // avoid compiler warnings

        // Register the session
        INT iKeyRegistered = XNetRegisterKey( &m_xnSessionID, &m_xnKeyExchangeKey );
        assert( iKeyRegistered == NO_ERROR );
        (VOID)iKeyRegistered; // avoid compiler warnings

        m_bIsSessionRegistered = TRUE;

        // Default to listen when System Link is chosen
        m_bListen = TRUE;
        SetListenState( m_bListen );

        // Set the response data to our session name
        SetListenData( m_strSessionName, 
                       ( lstrlenW( m_strSessionName ) + 1 ) * sizeof(WCHAR) );
    }

    if( !m_BroadSock.IsOpen() )
    {
        // Create broadcast socket for System Link testing
        // The broadcast socket is a non-blocking socket on port BROADCAST_PORT.
        BOOL bSuccess = m_BroadSock.Open( CXBSocket::Type_UDP );
        assert( bSuccess );
        (VOID)bSuccess;

        SOCKADDR_IN broadAddr;
        broadAddr.sin_family      = AF_INET;
        broadAddr.sin_addr.s_addr = INADDR_ANY;
        broadAddr.sin_port        = htons( BROADCAST_PORT );
        INT iResult = m_BroadSock.Bind( &broadAddr );
        assert( iResult != SOCKET_ERROR );
        DWORD dwNonBlocking = 1;
        iResult = m_BroadSock.IoCtlSocket( FIONBIO, &dwNonBlocking );
        assert( iResult != SOCKET_ERROR );
        BOOL bBroadcast = TRUE;
        iResult = m_BroadSock.SetSockOpt( SOL_SOCKET, SO_BROADCAST,
                                          &bBroadcast, sizeof(bBroadcast) );
        assert( iResult != SOCKET_ERROR );
    }
}




//-----------------------------------------------------------------------------
// Name: EndSysLinkListen()
// Desc: Clean up from System Link mode
//-----------------------------------------------------------------------------
VOID CXBoxSample::EndSysLinkListen()
{
    if( m_bIsSignedIn )
        return;

    // Release the listener and unregister the key
    if( m_bIsSessionRegistered )
    {
        // XNetUnregisterKey will automatically release the QoS listener
        INT iResult = XNetUnregisterKey( &m_xnSessionID );
        assert( iResult == NO_ERROR );
        (VOID)iResult;
        m_bIsSessionRegistered = FALSE;
        ZeroMemory( &m_xnSessionID, sizeof( XNKID ) );
    }

    // Close the socket used to find System Link sessions
    m_BroadSock.Close();
}

