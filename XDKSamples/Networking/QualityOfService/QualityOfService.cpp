// Desc: true if list is empty (emulates STL empty)
//-----------------------------------------------------------------------------
bool SessionList::empty() const
{
    return m_SessionList.empty();
}




//-----------------------------------------------------------------------------
// Name: size()
// Desc: Get the number of sessions in the list (emulates STL size)
//-----------------------------------------------------------------------------
DWORD SessionList::size() const
{
    return m_SessionList.size();
}




//-----------------------------------------------------------------------------
// Name: push_back()
// Desc: Add a session to the list (emulates STL push_back)
//-----------------------------------------------------------------------------
void SessionList::push_back( const XNADDR& xnAddr, const XNKID& xnKid, 
                             const XNKEY& xnKey )
{
    SessionData info;
    CopyMemory( &info.xnAddr, &xnAddr, sizeof( xnAddr ) );
    CopyMemory( &info.xnKid,  &xnKid,  sizeof( xnKid ) );
    CopyMemory( &info.xnKey,  &xnKey,  sizeof( xnKey ) );
    m_SessionList.push_back( info );

    SessionData* pInfo = &m_SessionList.back();

    // Save the addresses
    m_xnAddrList.push_back( &pInfo->xnAddr );
    m_xnKidList.push_back( &pInfo->xnKid );
    m_xnKeyList.push_back( &pInfo->xnKey );
}




//-----------------------------------------------------------------------------
// Name: clear()
// Desc: Remove all sessions from the list (emulates STL clear)
//-----------------------------------------------------------------------------
void SessionList::clear()
{
    // Remove items without freeing the memory
    m_SessionList.erase( m_SessionList.begin(), m_SessionList.end() );
    m_xnAddrList.erase( m_xnAddrList.begin(), m_xnAddrList.end() );
    m_xnKidList.erase( m_xnKidList.begin(), m_xnKidList.end() );
    m_xnKeyList.erase( m_xnKeyList.begin(), m_xnKeyList.end() );
}




