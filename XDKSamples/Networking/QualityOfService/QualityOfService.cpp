//-----------------------------------------------------------------------------
// Name: CXBoxSample()
// Desc: Constructor
//-----------------------------------------------------------------------------
CXBoxSample::CXBoxSample()
{
    m_State     = STATE_SELECT_MODE;
    m_NextState = STATE_SELECT_MODE;
    
    // Login to matchmaking service
    m_pServices[0] = XONLINE_MATCHMAKING_SERVICE;
    
    m_dwCurrItem  = 0;
    m_dwCurrUser  = 0;
    m_dwUserIndex = 0;
    
    m_bIsSessionRegistered = FALSE;
    m_bListen              = FALSE;
    m_bIsSignedIn          = FALSE;
    
    m_dwListenBandwidth = DEFAULT_LISTEN_BANDWIDTH;
    m_dwLookupBandwidth = DEFAULT_LOOKUP_BANDWIDTH;
    m_dwSamples         = DEFAULT_SAMPLES;
    
    *m_strSessionName = 0;
    
    ZeroMemory( &m_xnTitleAddress, sizeof( m_xnTitleAddress ) );
    ZeroMemory( &m_xnSessionID, sizeof( m_xnSessionID ) );
    ZeroMemory( &m_xnKeyExchangeKey, sizeof( m_xnKeyExchangeKey ) );

    // These structs are allocated by XNetQos[Service]Lookup and freed by
    // XNetQosRelease
    m_pxnQos = NULL;
    m_pxnServiceQos = NULL;
}




//-----------------------------------------------------------------------------
// Name: Initialize()
// Desc: Initialize device-dependant objects
//-----------------------------------------------------------------------------
HRESULT CXBoxSample::Initialize()
{
    // Initialize game UI
    if( FAILED( m_UI.Initialize() ) )
        return E_FAIL;
    
    // Initialize the network stack
    if( FAILED( XBNet_OnlineInit( XNET_STARTUP_BYPASS_SECURITY ) ) ) // &&&
        return E_FAIL;
    
    // Generate a session name that we can use with the probe data
    XBRandName_GetRandomName( m_strSessionName, MAX_SESSION_NAME );
    m_UI.SetSessionName( m_strSessionName );

    // Asynchronous local address acquisition. This would normally occur
    // during the game startup sequence. Only required for System Link.
    for( ;; )
    {
        DWORD dwStatus = XNetGetTitleXnAddr( &m_xnTitleAddress );
        assert( dwStatus != XNET_GET_XNADDR_NONE );

        // If we've retrieved the local address, we're done
        BOOL bHaveLocalAddr = ( dwStatus != XNET_GET_XNADDR_PENDING );
        if( bHaveLocalAddr )
            break;
    }

    return S_OK;
}




//-----------------------------------------------------------------------------
// Name: FrameMove()
// Desc: Called once per frame, the call is the entry point for animating
//       the scene.
//-----------------------------------------------------------------------------
HRESULT CXBoxSample::FrameMove()
{
    // Check the physical connection
    if( !m_NetLink.IsActive() )
    {
        m_UI.SetErrorStr( L"This Xbox has lost its network connection" );
        Reset();
    }

    // Maintain our connection once we've logged on
    if( m_bIsSignedIn )
    {
        HRESULT hr = m_hOnlineTask.Continue();    
        if( FAILED( hr ) )
        {
            m_UI.SetErrorStr( hr == XONLINE_E_LOGON_KICKED_BY_DUPLICATE_LOGON ?
                              L"You have been signed out because your\n"
                              L"account signed in on another Xbox." :
                              L"This Xbox has lost its network connection" );
            Reset();
        }
    }
    
    Event ev = GetEvent();
    
    switch( m_State )
    {
    // System Link
    case STATE_SYSLINK_SEARCH:       UpdateStateSysLinkSearch( ev );      break;

    // Online
    case STATE_CREATE_ACCOUNT:       UpdateStateCreateAccount( ev );      break;
    case STATE_SELECT_ACCOUNT:       UpdateStateSelectAccount( ev );      break;
    case STATE_SIGNING_IN:           UpdateStateSigningIn( ev );          break;
    case STATE_ONLINE_CREATE:        UpdateStateOnlineCreate( ev );       break;
    case STATE_ONLINE_SEARCH:        UpdateStateOnlineSearch( ev );       break;

    // Generic
    case STATE_SELECT_MODE:          UpdateStateSelectMode( ev );         break;
    case STATE_SELECT_LISTEN_PARAMS: UpdateStateSelectListenParams( ev ); break;
    case STATE_SESSION_LIST:         UpdateStateSessionList( ev );        break;
    case STATE_SHOW_PROBE_DATA:      UpdateStateShowProbeData( ev );      break;
    case STATE_ERROR:                UpdateStateError( ev );              break;
    case STATE_HELP:                 UpdateStateHelp( ev );               break;

    default:                         assert( FALSE );                     break;
    }
    
    return S_OK;
}




//-----------------------------------------------------------------------------
// Name: Render()
// Desc: Called once per frame, the call is the entry point for 3D
//       rendering. This function sets up render states, clears the
//       viewport, and renders the scene.
//-----------------------------------------------------------------------------
HRESULT CXBoxSample::Render()
{
    // Clear the viewport
    m_pd3dDevice->Clear( 0L, NULL, D3DCLEAR_TARGET|D3DCLEAR_ZBUFFER|D3DCLEAR_STENCIL, 
        0x000A0A6A, 1.0f, 0L );
    
    switch( m_State )
    {
    case STATE_SYSLINK_SEARCH: m_UI.RenderSysLinkSearch();       break;
    case STATE_CREATE_ACCOUNT: m_UI.RenderCreateAccount( TRUE ); break;
    case STATE_SIGNING_IN:     m_UI.RenderSigningIn();           break;
    case STATE_ONLINE_CREATE:  m_UI.RenderOnlineCreate();        break;
    case STATE_ONLINE_SEARCH:  m_UI.RenderOnlineSearch();        break;
    case STATE_SELECT_MODE:    m_UI.RenderMode( m_dwCurrItem );  break;
    case STATE_ERROR:          m_UI.RenderError();               break;
    case STATE_HELP:           m_UI.RenderHelp();                break;

    case STATE_SELECT_LISTEN_PARAMS:
        m_UI.RenderListenParams( m_dwCurrItem, m_bListen, m_dwSamples, 
                                 m_dwListenBandwidth, m_dwLookupBandwidth, 
                                 m_bIsSignedIn );
        break;
    case STATE_SESSION_LIST:
        m_UI.RenderSessionList( m_dwCurrItem, m_xnTitleAddress, m_Sessions, 
                                m_pxnQos, m_pxnServiceQos,
                                m_dwSamples, m_bIsSignedIn ); 
        break;
    case STATE_SHOW_PROBE_DATA:
        m_UI.RenderProbeData( m_dwCurrItem, m_strSessionName, m_xnTitleAddress,
                              m_Sessions, m_pxnQos, m_pxnServiceQos, m_bIsSignedIn );
        break;
    case STATE_SELECT_ACCOUNT:
        m_UI.RenderSelectAccount( m_dwCurrItem, m_UserList );
        break;
    default:
        assert( FALSE );
        break;
    }
    
    // Present the scene
    m_pd3dDevice->Present( NULL, NULL, NULL, NULL );
    
    return S_OK;
}




