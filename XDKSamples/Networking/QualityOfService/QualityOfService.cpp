//-----------------------------------------------------------------------------
// Message IDs
//-----------------------------------------------------------------------------
enum
{
    MSG_FIND_SESSION,
    MSG_SESSION_FOUND,
};




//-----------------------------------------------------------------------------
// Message payloads
//-----------------------------------------------------------------------------
// Pack to minimize network traffic
#pragma pack( push )
#pragma pack( 1 )

//-----------------------------------------------------------------------------
// Broadcast by a SysLink client looking for available sessions
//-----------------------------------------------------------------------------
struct MsgFindSession
{
    Nonce nonce;    // Generated by client; used to verify host response
};

//-----------------------------------------------------------------------------
// Broadcast by a SysLink host in response to a MSG_FIND_SESSION
//-----------------------------------------------------------------------------
struct MsgSessionFound
{
    Nonce  nonce;   // used for client verification
    XNADDR xnAddr;  // host XNet address
    XNKID  xnKid;   // host key ID
    XNKEY  xnKey;   // host key
};

#pragma pack( pop )




//-----------------------------------------------------------------------------
// Name: class Message
// Desc: Message object
//-----------------------------------------------------------------------------
class Message
{
    BYTE m_byMessageId;

    union
    {
        MsgFindSession     m_FindSession;
        MsgSessionFound    m_SessionFound;
    };

public:

    explicit Message( BYTE byMessageId = 0 ) : m_byMessageId( byMessageId ) {}
    ~Message() {}

    BYTE GetId() const      { return m_byMessageId; }
    INT  GetMaxSize() const { return sizeof(*this); }

    MsgFindSession&     GetFindSession()     { return m_FindSession;     }
    MsgSessionFound&    GetSessionFound()    { return m_SessionFound;    }

    INT GetSize() const
    { 
        switch( m_byMessageId )
        {
            case MSG_FIND_SESSION:     return sizeof(BYTE) + sizeof(MsgFindSession);
            case MSG_SESSION_FOUND:    return sizeof(BYTE) + sizeof(MsgSessionFound);
            default: assert( FALSE ); return 0;
        }
    }

private:

    // Disabled
    Message( const Message& );
    Message& operator=( const Message& );

};




