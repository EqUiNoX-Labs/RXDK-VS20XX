//-----------------------------------------------------------------------------
// Name: GetEvent()
// Desc: Return the state of the controller
//-----------------------------------------------------------------------------
CXBoxSample::Event CXBoxSample::GetEvent() const
{
    // "A" or "Start"
    if( m_DefaultGamepad.bPressedAnalogButtons[ XINPUT_GAMEPAD_A ] ||
        m_DefaultGamepad.wPressedButtons & XINPUT_GAMEPAD_START )
    {
        return EV_BUTTON_A;
    }
    
    // "B"
    if( m_DefaultGamepad.bPressedAnalogButtons[ XINPUT_GAMEPAD_B ] )
        return EV_BUTTON_B;
    
    // "Back"
    if( m_DefaultGamepad.wPressedButtons & XINPUT_GAMEPAD_BACK )
        return EV_BUTTON_BACK;

     // "White"
    if( m_DefaultGamepad.bPressedAnalogButtons[ XINPUT_GAMEPAD_WHITE ] )
        return EV_BUTTON_WHITE;
   
    // Movement
    if( m_DefaultGamepad.wPressedButtons & XINPUT_GAMEPAD_DPAD_UP )
        return EV_UP;
    if( m_DefaultGamepad.wPressedButtons & XINPUT_GAMEPAD_DPAD_DOWN )
        return EV_DOWN;
    if( m_DefaultGamepad.wPressedButtons & XINPUT_GAMEPAD_DPAD_LEFT )
        return EV_LEFT;
    if( m_DefaultGamepad.wPressedButtons & XINPUT_GAMEPAD_DPAD_RIGHT )
        return EV_RIGHT;
    
    return EV_NULL;
}



//-----------------------------------------------------------------------------
// Name: UpdateStateSelectMode()
// Desc: Choose between System Link and Online
//-----------------------------------------------------------------------------
VOID CXBoxSample::UpdateStateSelectMode( Event ev )
{
    switch( ev )
    {
    case EV_BUTTON_A:
        switch( m_dwCurrItem )
        {
        case MENU_SYSLINK:
            EndOnlineListen();
            BeginSysLinkListen();
            m_State = STATE_SELECT_LISTEN_PARAMS;
            m_dwCurrItem = 0;
            break;

        case MENU_ONLINE:
            EndSysLinkListen();
            m_State = STATE_SELECT_ACCOUNT;
            m_dwCurrItem = 0;
            GetOnlineUsers();
            break;

        default:
            assert( false );
            break;
        }
        break;
        
    case EV_UP:
        // Move to previous item; allow wrap to bottom
        if( m_dwCurrItem == 0 )
            m_dwCurrItem = MENU_MODE_MAX - 1;
        else
            --m_dwCurrItem;
        break;
        
    case EV_DOWN:
        // Move to next item; allow wrap to top
        if( m_dwCurrItem == MENU_MODE_MAX - 1 )
            m_dwCurrItem = 0;
        else
            ++m_dwCurrItem;
        break;

    case EV_BUTTON_WHITE:
        m_NextState = m_State;
        m_State = STATE_HELP;
        break;
    }
}




//-----------------------------------------------------------------------------
// Name: UpdateStateSysLinkSearch()
// Desc: Search for SysLink sessions
//-----------------------------------------------------------------------------
VOID CXBoxSample::UpdateStateSysLinkSearch( Event ev )
{
    // See if any consoles have replied
    if( ProcessBroadcastMessage() )
        return;

    // We search for up to SESSION_SEARCH_TIME seconds. If the session 
    // search is complete, display the list of sessions. If no sessions
    // were found, display an error message
    if( m_SysLinkSearchTimer.GetElapsedSeconds() > SESSION_SEARCH_TIME )
    {
        m_SysLinkSearchTimer.Stop();
        if( m_Sessions.empty() )
        {
            m_UI.SetErrorStr( L"No System Link sessions available" );
            Reset();
        }
        else // at least one session
        {
            BeginQosLookup();
            m_State = STATE_SESSION_LIST;
        }
    }
}




//-----------------------------------------------------------------------------
// Name: UpdateStateCreateAccount()
// Desc: Inform player that account must be generated using external tool
//-----------------------------------------------------------------------------
VOID CXBoxSample::UpdateStateCreateAccount( Event ev )
{
    switch( ev )
    {
    case EV_BUTTON_A:
        // Return to Dashboard. Retail Dashboard will include online account 
        // creation. Development XDK includes the XDK Launcher or Xbox 
        // OnlineDash for creating accounts.
        LD_LAUNCH_DASHBOARD ld;
        ZeroMemory( &ld, sizeof(ld) );
        ld.dwReason = XLD_LAUNCH_DASHBOARD_NEW_ACCOUNT_SIGNUP;
        XLaunchNewImage( NULL, PLAUNCH_DATA( &ld ) );
        break;

    case EV_BUTTON_WHITE:
        m_NextState = m_State;
        m_State = STATE_HELP;
        break;

    default:
        // If any MUs are inserted, update the user list
        // and go to account selection if there are any accounts
        DWORD dwInsertions;
        DWORD dwRemovals;
        if( CXBMemUnit::GetMemUnitChanges( dwInsertions, dwRemovals ) )
        {
            m_UserList.clear();
            XBOnline_GetUserList( m_UserList );
            if( !m_UserList.empty() )
            {
                m_dwCurrItem = 0;
                m_State = STATE_SELECT_ACCOUNT;
            }
       }
        break;
        
    }
}




//-----------------------------------------------------------------------------
// Name: UpdateStateSelectAccount()
// Desc: Allow player to select user account
//-----------------------------------------------------------------------------
VOID CXBoxSample::UpdateStateSelectAccount( Event ev )
{
    // If player is already logged on, proceed to online session creation
    if( m_bIsSignedIn )
    {
        m_State = STATE_ONLINE_CREATE;
        return;
    }

    switch( ev )
    {
    case EV_BUTTON_A:
        // Save current account information
        m_dwCurrUser = m_dwCurrItem;

        // Sign in
        m_State = STATE_SIGNING_IN;
        BeginSignIn();
        break;
        
    case EV_BUTTON_B:
    case EV_BUTTON_BACK:
        m_dwCurrItem = 0;
        m_State = STATE_SELECT_MODE;
        break;
        
    case EV_UP:
        // Move to previous user account; allow wrap to bottom
        if( m_dwCurrItem == 0 )
            m_dwCurrItem = m_UserList.size() - 1;
        else
            --m_dwCurrItem;
        break;
        
    case EV_DOWN:
        // Move to next user account; allow wrap to top
        if( m_dwCurrItem == m_UserList.size() - 1 )
            m_dwCurrItem = 0;
        else
            ++m_dwCurrItem;
        break;
        
    case EV_BUTTON_WHITE:
        m_NextState = m_State;
        m_State = STATE_HELP;
        break;

    default:
        // If any MUs are inserted/removed, need to update the
        // user account list
        DWORD dwInsertions;
        DWORD dwRemovals;
        if( CXBMemUnit::GetMemUnitChanges( dwInsertions, dwRemovals ) )
        {
            m_UserList.clear();
            XBOnline_GetUserList( m_UserList );
            if( m_UserList.empty() )
                m_State = STATE_CREATE_ACCOUNT;
            else
                m_dwCurrItem = 0;
        }
        break;
    }
}




//-----------------------------------------------------------------------------
// Name: UpdateStateSigningIn()
// Desc: Spin during authentication
//-----------------------------------------------------------------------------
VOID CXBoxSample::UpdateStateSigningIn( Event ev )
{
    switch( ev )
    {
    case EV_BUTTON_B:
    case EV_BUTTON_BACK:
        
        // Cancel the task
        m_hOnlineTask.Close();
        m_State = STATE_SELECT_ACCOUNT;
        return;
    }

    // Pump the sign in task    
    HRESULT hr = m_hOnlineTask.Continue();
    
    if( FAILED( hr ) )
    {
        m_UI.SetErrorStr( L"Sign In failed with error %x from TaskContinue", hr );
        m_hOnlineTask.Close();
        m_State = STATE_ERROR;
        m_NextState = STATE_SELECT_ACCOUNT;
        return;
    }
    
    // Check sign in status to see if it has completed
    if( hr == XONLINE_S_LOGON_CONNECTION_ESTABLISHED )
    {
        BOOL bSuccess = TRUE;
        HRESULT hrService = S_OK;
        
        // Next, check if the user was actually logged on
        PXONLINE_USER pLoggedOnUsers = XOnlineGetLogonUsers();
        assert( pLoggedOnUsers );
        hr = pLoggedOnUsers[ m_dwUserIndex ].hr;
        
        if( FAILED( hr ) )
        {
            m_UI.SetErrorStr( L"User Sign In failed with error %x", hr );
            bSuccess = FALSE;
        }
        else
        {
            // Check for service errors
            for( DWORD i = 0; i < NUM_SERVICES; ++i )
            {
                hrService = XOnlineGetServiceInfo( m_pServices[i], NULL );
                if( FAILED( hrService ) )
                {
                    m_UI.SetErrorStr( L"Service %d Sign In failed with error %x",
                                      m_pServices[i], hrService );
                    bSuccess = FALSE;
                    break;
                }
            }
        }
        
        if( bSuccess )
        {
            // We're now authenticated with Xbox Live
            m_bIsSignedIn = TRUE;
            
            // Start up an online session
            m_dwCurrItem = 0;

            m_State = STATE_ONLINE_CREATE;
            BeginOnlineSession();
        }
        else
        {
            // We failed to authenticate
            m_hOnlineTask.Close();
            m_State = STATE_ERROR;
            m_NextState = STATE_SELECT_ACCOUNT;
        }
    }
}




//-----------------------------------------------------------------------------
// Name: UpdateStateOnlineCreate()
// Desc: Creating session
//-----------------------------------------------------------------------------
VOID CXBoxSample::UpdateStateOnlineCreate( Event ev )
{
    // If session already exists, proceed to QoS parameters
    if( m_bIsSessionRegistered )
    {
        m_dwCurrItem = 0;
        m_State = STATE_SELECT_LISTEN_PARAMS;
        return;
    }

    // Wait for matchmaking server to save new session info
    HRESULT hr = m_hMatchCreateTask.Continue();
    if( hr == XONLINETASK_S_RUNNING )
        return;

    // Handle errors
    if( FAILED(hr) )
    {
        m_UI.SetErrorStr( L"Session creation failed with error %x", hr );
        Reset();
        return;
    }

    // Extract the new session ID
    hr = XOnlineMatchSessionGetInfo( m_hMatchCreateTask, &m_xnSessionID, 
                                     &m_xnKeyExchangeKey );
    
    // Handle errors
    if( FAILED(hr) )
    {
        m_UI.SetErrorStr( L"XOnlineMatchSessionGetInfo failed with error %x",
                          hr );
        Reset();
        return;
    }

    // Session was created by matchmaking server. Now register the
    // session with this console.
    assert( !m_bIsSessionRegistered );
    INT iKeyRegistered = XNetRegisterKey( &m_xnSessionID, &m_xnKeyExchangeKey );
    if( iKeyRegistered != NO_ERROR )
    {
        m_UI.SetErrorStr( L"XNetRegisterKey failed");
        Reset();
        return;
    }

    // Now that the session is registered, we can begin listening for probes
    // from other consoles.     
    m_hMatchCreateTask.Close();
    m_bIsSessionRegistered = TRUE;
    BeginOnlineListen();

    // Allow user to select parameters
    m_State = STATE_SELECT_LISTEN_PARAMS;
    m_dwCurrItem = 0;
}




//-----------------------------------------------------------------------------
// Name: UpdateStateOnlineSearch()
// Desc: Searching for matching game session(s)
//-----------------------------------------------------------------------------
VOID CXBoxSample::UpdateStateOnlineSearch( Event ev )
{
    assert( m_hMatchSearchTask != NULL );

    // Wait for matchmaking server to return results
    HRESULT hr = m_hMatchSearchTask.Continue();
    if( hr == XONLINETASK_S_RUNNING )
        return;

    // Handle errors
    if( FAILED(hr) )
    {
        m_UI.SetErrorStr( L"Session search failed with error %x", hr );
        Reset();
        return;
    }
    
    // Get the list returned by the matchmaking server
    PXONLINE_MATCH_SEARCHRESULT* ppSearchResult;
    DWORD dwResults;
    hr = XOnlineMatchSearchGetResults( m_hMatchSearchTask, &ppSearchResult,
                                       &dwResults );
    
    // Handle errors
    if( FAILED(hr) )
    {
        m_UI.SetErrorStr( L"Session search get results failed with error %x", hr );
        Reset();
        return;
    }

    // Save the results
    m_Sessions.clear();
    for( DWORD i = 0; i < dwResults; ++i )
    {
        m_Sessions.push_back( ppSearchResult[ i ]->HostAddress,
                              ppSearchResult[ i ]->SessionID,
                              ppSearchResult[ i ]->KeyExchangeKey );
    }
    
    // The search is over
    m_hMatchSearchTask.Close();

    // Bail out if no online sessions
    if( m_Sessions.empty() )
    {
        m_UI.SetErrorStr( L"No Online sessions available" );
        Reset();
        return;
    }

    // At least one online session
    BeginQosLookup();
    m_State = STATE_SESSION_LIST;
    m_dwCurrItem = 0;
}




//-----------------------------------------------------------------------------
// Name: UpdateStateSelectListenParams()
// Desc: Set the listener parameters
//-----------------------------------------------------------------------------
VOID CXBoxSample::UpdateStateSelectListenParams( Event ev )
{
    // Handle any find session messages
    if( ProcessBroadcastMessage() )
        return;

    switch( ev )
    {
    case EV_BUTTON_A:
        switch( m_dwCurrItem )
        {
        case MENU_START_LOOKUPS:
            if( XNetXnKidIsSystemLink( &m_xnSessionID ) )
            {
                // Search for other System Link consoles running this title ID
                assert( !m_bIsSignedIn );
                m_State = STATE_SYSLINK_SEARCH;

                // Add ourself, to emulate the online case
                m_Sessions.clear();
                m_Sessions.push_back( m_xnTitleAddress, m_xnSessionID, 
                                      m_xnKeyExchangeKey );

                // Start looking for other System Link consoles
                SendFindSession();
                m_SysLinkSearchTimer.StartZero();
            }
            else
            {
                // Search for other Online consoles running this title ID
                assert( m_bIsSignedIn );
                m_State = STATE_ONLINE_SEARCH;
                BeginOnlineSearch();
            }
            break;

        case MENU_SET_LISTEN_STATE:
            // Update the listen state
            m_bListen = !m_bListen;
            SetListenState( m_bListen );
            break;
        
        default:
            break;
        }
        break;
        
    case EV_BUTTON_B:
        m_dwCurrItem = 0;
        m_State = STATE_SELECT_MODE;
        break;
        
    case EV_UP:
        // Move to previous item; allow wrap to bottom
        if( m_dwCurrItem == 0 )
            m_dwCurrItem = MENU_LISTEN_PARAMS_MAX - 1;
        else
            --m_dwCurrItem;
        break;
        
    case EV_DOWN:
        // Move to next item; allow wrap to top
        if( m_dwCurrItem == MENU_LISTEN_PARAMS_MAX - 1 )
            m_dwCurrItem = 0;
        else
            ++m_dwCurrItem;
        break;

    case EV_LEFT:
        // Move sliders
        switch( m_dwCurrItem )
        {
        case MENU_SET_LISTEN_STATE:
            m_bListen = !m_bListen;
            SetListenState( m_bListen );
            break;
        case MENU_NUM_SAMPLES:
            if( m_dwSamples > 0 )
                --m_dwSamples;
            break;
        case MENU_LISTEN_BANDWIDTH:
            if( m_dwListenBandwidth > MIN_LISTEN_BANDWIDTH &&
                m_dwListenBandwidth >= LISTEN_BANDWIDTH_CHUNK )
            {
                m_dwListenBandwidth -= LISTEN_BANDWIDTH_CHUNK;
                SetListenBitsPerSec( m_dwListenBandwidth );
            }
            break;
        case MENU_LOOKUP_BANDWIDTH:
            if( m_dwLookupBandwidth > MIN_LOOKUP_BANDWIDTH &&
                m_dwLookupBandwidth >= LOOKUP_BANDWIDTH_CHUNK )
                m_dwLookupBandwidth -= LOOKUP_BANDWIDTH_CHUNK;
            break;
        }
        break;

    case EV_RIGHT:
        // Move sliders
        switch( m_dwCurrItem )
        {
        case MENU_SET_LISTEN_STATE:
            m_bListen = !m_bListen;
            SetListenState( m_bListen );
            break;
        case MENU_NUM_SAMPLES:
            if( m_dwSamples < MAX_SAMPLES )
                ++m_dwSamples;
            break;
        case MENU_LISTEN_BANDWIDTH:
            if( m_dwListenBandwidth < LISTEN_BANDWIDTH_MAX )
            {
                m_dwListenBandwidth += LISTEN_BANDWIDTH_CHUNK;
                SetListenBitsPerSec( m_dwListenBandwidth );
            }
            break;
        case MENU_LOOKUP_BANDWIDTH:
            if( m_dwLookupBandwidth < LOOKUP_BANDWIDTH_MAX )
                m_dwLookupBandwidth += LOOKUP_BANDWIDTH_CHUNK;
            break;
        }
        break;

    case EV_BUTTON_WHITE:
        m_NextState = m_State;
        m_State = STATE_HELP;
        break;
    }
}




