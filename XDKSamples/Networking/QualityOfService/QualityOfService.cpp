//-----------------------------------------------------------------------------
// Name: SendFindSession()
// Desc: Broadcast a MSG_FIND_SESSION from our client to any available host.
//       Used for System Link only
//-----------------------------------------------------------------------------
VOID CXBoxSample::SendFindSession()
{
    Message msgFindSession( MSG_FIND_SESSION );
    MsgFindSession& msg = msgFindSession.GetFindSession();

    // Generate a nonce (random bytes). When a potential host responds with
    // information about a session, he must respond via a broadcast message
    // since a secure session hasn't been established. The broadcast message
    // will contain the same nonce so we can verify that message is really
    // for us. If we receive a broadcast "found session" message with a different
    // nonce, we ignore it, because it was broadcast to a different client
    // than us.
    INT iResult = XNetRandom( (BYTE*)(&msg.nonce), sizeof(msg.nonce) );
    assert( iResult == NO_ERROR );
    (VOID)iResult;

    // Save the nonce for comparison later
    CopyMemory( &m_Nonce, &msg.nonce, sizeof(msg.nonce) );

    SOCKADDR_IN saBroad;
    saBroad.sin_family      = AF_INET;
    saBroad.sin_addr.s_addr = INADDR_BROADCAST;
    saBroad.sin_port        = htons( BROADCAST_PORT );
    INT nBytes = m_BroadSock.SendTo( &msgFindSession, msgFindSession.GetSize(),
                                     &saBroad );
    // This assert was removed because Send no longer is guaranteed to always work
    // If the security association times out, the number of bytes returned will 
    // NOT be equal to the size of the message.  A good thing to do here would
    // be to drop the player
    //assert( nBytes == msgFindSession.GetSize() );
    (VOID)nBytes;
}




//-----------------------------------------------------------------------------
// Name: SendSessionFound()
// Desc: Broadcast a MSG_SESSION_FOUND from our host to the world.
//       Used for System Link only
//-----------------------------------------------------------------------------
VOID CXBoxSample::SendSessionFound( const Nonce& nonceClient )
{
    Message msgSessionFound( MSG_SESSION_FOUND );
    MsgSessionFound& msg = msgSessionFound.GetSessionFound();

    // Resend the nonce that we received from the client so he can verify
    // that this message is really for him
    CopyMemory( &msg.nonce, &nonceClient, sizeof(nonceClient) );

    // Send information about us so the client can issue a QoS lookup
    CopyMemory( &msg.xnAddr, &m_xnTitleAddress,   sizeof(XNADDR) );
    CopyMemory( &msg.xnKid,  &m_xnSessionID,      sizeof(XNKID) );
    CopyMemory( &msg.xnKey,  &m_xnKeyExchangeKey, sizeof(XNKEY) );

    // We don't have the XNADDR of the requesting client, so we
    // can't send this message directly back. Instead, we broadcast the
    // message to everybody on the net. The requesting client can
    // check the nonce to verify that the response is really for them.

    SOCKADDR_IN saBroad;
    saBroad.sin_family      = AF_INET;
    saBroad.sin_addr.s_addr = INADDR_BROADCAST;
    saBroad.sin_port        = htons( BROADCAST_PORT );
    INT nBytes = m_BroadSock.SendTo( &msgSessionFound, msgSessionFound.GetSize(),
                                     &saBroad );
    // This assert was removed because Send no longer is guaranteed to always work
    // If the security association times out, the number of bytes returned will 
    // NOT be equal to the size of the message.  A good thing to do here would
    // be to drop the player
    //assert( nBytes == msgSessionFound.GetSize() );
    (VOID)nBytes;
}




//-----------------------------------------------------------------------------
// Name: ProcessBroadcastMessage()
// Desc: Checks to see if any broadcast messages are waiting on the broadcast
//       socket. If a message is waiting, it is routed and processed.
//       If no messages are waiting, the function returns immediately.
//       Returns TRUE if a message was processed. Used for System Link only.
//-----------------------------------------------------------------------------
BOOL CXBoxSample::ProcessBroadcastMessage()
{
    if( !m_BroadSock.IsOpen() )
        return FALSE;

    // See if a network broadcast message is waiting for us
    Message msg;
    INT iResult = m_BroadSock.Recv( &msg, msg.GetMaxSize() );

    // If message waiting, process it
    if( iResult != SOCKET_ERROR && iResult > 0 )
    {
        assert( iResult == msg.GetSize() );

        // Process the message
        switch( msg.GetId() )
        {
            case MSG_FIND_SESSION:  ProcessFindSession( msg.GetFindSession() ); break;
            case MSG_SESSION_FOUND: ProcessSessionFound( msg.GetSessionFound() ); break;
            default: assert( FALSE ); break;
        }
        return TRUE;
    }
    return FALSE;
}




//-----------------------------------------------------------------------------
// Name: ProcessFindSession()
// Desc: Process the find session message. Used for System Link only.
//-----------------------------------------------------------------------------
VOID CXBoxSample::ProcessFindSession( const MsgFindSession& findSession )
{
    // Respond with the information about this session
    SendSessionFound( findSession.nonce );
}




//-----------------------------------------------------------------------------
// Name: ProcessSessionFound()
// Desc: Process the session found message. Used for System Link only.
//-----------------------------------------------------------------------------
VOID CXBoxSample::ProcessSessionFound( const MsgSessionFound& sessionFound )
{
    // If we didn't send the corresponding "find session" message, we don't
    // care about this particular "session found" message
    if( memcmp( &sessionFound.nonce, &m_Nonce, NONCE_BYTES ) != 0 )
        return;

    // We found a session on another console!
    // Add it to our list of potential sessions

    m_Sessions.push_back( sessionFound.xnAddr, sessionFound.xnKid,
                          sessionFound.xnKey );

    // If the list is full, move on to the next stage
    if( m_Sessions.size() == MAX_SESSIONS )
    {
        BeginQosLookup();
        m_State = STATE_SESSION_LIST;
    }
}




//-----------------------------------------------------------------------------
// Name: BeginQosLookup()
// Desc: Initiate the QoS lookup
//-----------------------------------------------------------------------------
VOID CXBoxSample::BeginQosLookup()
{
    // If online, query the Matchmaking Security Gateway, too. There are 
    // two ways to probe SGs. The deprecated method is to use parameters 
    // 5-7 of XNetQosLookup. The new way is to use XNetQosServiceLookup.
    // For completeness, this code shows both methods.
    
    // NOTE: Resulting bandwidth values are only rough estimates, and are not
    // always accurate indicators of true bandwidth conditions. They are only
    // useful in comparing relative bandwidths of various consoles, and should
    // not be diplayed or used to set player maximums or other similar game 
    // restrictions.
    
    XONLINE_SERVICE_INFO info;
    IN_ADDR* pSecurityGateway = NULL;
    DWORD* pServiceID = NULL;
    DWORD dwSecurityGateway = 0;
    if( m_bIsSignedIn )
    {
        // m_pServices[0] is XONLINE_MATCHMAKING_SERVICE
        HRESULT hr = XOnlineGetServiceInfo( m_pServices[0], &info );
        
        // Obtain the service info for XNetQosLookup
        if( SUCCEEDED(hr) )
        {
            dwSecurityGateway = 1;
            pSecurityGateway = &info.serviceIP;
            pServiceID = &info.dwServiceID;
        }
    }

    INT iResult = XNetQosLookup( m_Sessions.size(),
                                 m_Sessions.GetXnAddrs(),
                                 m_Sessions.GetXnKids(),
                                 m_Sessions.GetXnKeys(),
                                 dwSecurityGateway,   // Security Gateways
                                 pSecurityGateway,    // SG IN_ADDRs
                                 pServiceID,          // SG service IDs
                                 m_dwSamples,         // Probe samples
                                 m_dwLookupBandwidth, // lookup bandwidth max
                                 0,                   // flags
                                 NULL,                // optional event
                                 &m_pxnQos );

    assert( iResult == NO_ERROR );
    (VOID)iResult;

    // The heavyweight method of determining SG bandwidth    
    if( m_bIsSignedIn )
    {
        // Automatically uses 24 probes of significantly larger 
        // sizes than XNetQosLookup to make a better
        // bandwidth estimate (though still far from perfect).
        // Automatically uses a maximum lookup bandwidth of 64 Kb/s.
        iResult = XNetQosServiceLookup( 0, NULL, &m_pxnServiceQos );
        assert( iResult == NO_ERROR );
    }
}




